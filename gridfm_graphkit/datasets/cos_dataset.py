"""
Lazy-loading PyTorch dataset backed by Cloud Object Storage (COS).

See :class:`COSHeteroGridDataset` for details.
"""

from __future__ import annotations

import torch
from pathlib import Path
from typing import Optional, Callable

from gridfm_graphkit.datasets.cos_utils import (
    parse_cos_url,
    _make_cache_dir,
    _get_s3_client,
    download_file_from_cos,
)


class COSHeteroGridDataset:
    """Lazy-loading power-grid dataset backed by Cloud Object Storage.

    Each processed graph file (``processed/data_index_{idx}.pt``) is
    downloaded from COS **only when** ``dataset[idx]`` is accessed.
    No files are downloaded at construction time.

    The COS bucket/prefix is expected to contain already-processed files
    that were previously generated by :class:`HeteroGridDatasetDisk`, i.e.::

        <prefix>/processed/data_index_0.pt
        <prefix>/processed/data_index_1.pt
        …
        <prefix>/processed/load_scenarios.pt   (optional)

    Parameters
    ----------
    cos_url:
        Full COS URL, e.g.
        ``cos://key:secret@endpoint:port/bucket/path/to/network``.
    data_normalizer:
        Normalizer applied at access time (must be fitted externally).
    transform:
        Optional transform applied at access time.
    cache_dir:
        Base directory for the local file cache.
        Defaults to ``$TMPDIR/gridfm_cos_cache``.
    force_download:
        When ``True``, existing cached files are overwritten.
    """

    def __init__(
        self,
        cos_url: str,
        data_normalizer,
        transform: Optional[Callable] = None,
        cache_dir: str | None = None,
        force_download: bool = False,
    ) -> None:
        self._cos_params = parse_cos_url(cos_url)
        self.data_normalizer = data_normalizer
        self.transform = transform
        self._force = force_download
        self._local_dir = _make_cache_dir(
            self._cos_params["endpoint_url"],
            self._cos_params["bucket"],
            self._cos_params["prefix"],
            cache_dir,
        )
        self._length: int | None = None

        # Eagerly fetch load_scenarios.pt — it is small metadata used by the
        # datamodule split logic.  We mirror HeteroGridDatasetDisk: the
        # attribute is set only when the file is actually present.
        ls_local = self._local_dir / "processed" / "load_scenarios.pt"
        if not ls_local.exists():
            try:
                download_file_from_cos(
                    self._cos_params,
                    "processed/load_scenarios.pt",
                    self._local_dir,
                )
            except Exception:
                pass  # file does not exist on COS — that is fine
        if ls_local.exists():
            self.load_scenarios = torch.load(str(ls_local), weights_only=True)

    # ------------------------------------------------------------------
    # Dataset interface
    # ------------------------------------------------------------------

    def __len__(self) -> int:
        if self._length is None:
            self._length = self._count_processed_files()
        return self._length

    def __getitem__(self, idx: int):
        from torch_geometric.data import HeteroData

        relative = f"processed/data_index_{idx}.pt"
        local_file = download_file_from_cos(
            self._cos_params,
            relative,
            self._local_dir,
            force=self._force,
        )
        data_dict = torch.load(str(local_file), weights_only=True)
        data = HeteroData.from_dict(data_dict)
        self.data_normalizer.transform(data=data)
        if self.transform is not None:
            data = self.transform(data)
        return data

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _count_processed_files(self) -> int:
        """Count ``data_index_*.pt`` objects under the COS prefix."""
        s3 = _get_s3_client(self._cos_params)
        bucket = self._cos_params["bucket"]
        prefix = self._cos_params["prefix"].rstrip("/")
        search_prefix = f"{prefix}/processed/data_index_" if prefix else "processed/data_index_"

        paginator = s3.get_paginator("list_objects_v2")
        return sum(
            1
            for page in paginator.paginate(Bucket=bucket, Prefix=search_prefix)
            for obj in page.get("Contents", [])
            if obj["Key"].endswith(".pt")
        )
